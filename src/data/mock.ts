export const makeLyrics = (lines: string[], start = 5.5, lineDur = 4.0, gap = 0.6): LyricLine[] =>
  lines.map((text, i) => {
    const s = start + i * (lineDur + gap);
    return { start: s, end: s + lineDur, text };
  });

